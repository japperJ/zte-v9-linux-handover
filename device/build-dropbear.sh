#!/bin/bash
# Cross-build dropbear + dropbearkey for the ZTE V9 (ARMv6, static musl).
#
# Why this exists: the build machine has no make and no gcc, so the object
# lists are lifted straight from the upstream Makefiles and every translation
# unit is compiled individually with `zig cc`.
#
# Usage:
#   ./build-dropbear.sh                    # expects ./dropbear-2022.83 next to this script
#   SRC=/path/to/dropbear-2022.83 ./build-dropbear.sh
#   ZIG=/path/to/zig ./build-dropbear.sh
#
# Produces ./dropbear-2022.83/{dropbear,dropbearkey} (static ARM EABI5).
# Both libtom archives are cached; delete them to force a full rebuild.
set -u

HERE=$(cd "$(dirname "$0")" && pwd)
SRC=${SRC:-$HERE/dropbear-2022.83}
ZIG=${ZIG:-$(command -v zig 2>/dev/null)}

[ -n "$ZIG" ] || { echo "zig not found; set ZIG=/path/to/zig"; exit 1; }
[ -d "$SRC" ] || { echo "dropbear source not found at $SRC"; exit 1; }

TARGET="-target arm-linux-musleabi -mcpu=arm1136j_s"
BASE="-Os -fno-strict-overflow -Wno-pointer-sign"
cc() { "$ZIG" cc $TARGET $BASE "$@"; }

cd "$SRC" || exit 1

# configure is required for config.h and for the three Makefiles that the object
# lists are scraped from. It only needs a shell, so it works without make/gcc.
if [ ! -f config.h ] || [ ! -f Makefile ]; then
  echo "### configure"
  CC="$ZIG cc $TARGET" ./configure --host=arm-linux \
    --disable-zlib --disable-lastlog --disable-utmpx --disable-wtmp \
    --disable-syslog --disable-harden || exit 1
fi

# Pull a whitespace-separated object list out of a makefile OBJECTS= block.
objlist() {
  awk '
    /^OBJECTS[ \t]*=/ { f=1 }
    f {
      line=$0
      cont = (line ~ /\\$/)
      gsub(/\\/, "", line)
      sub(/^OBJECTS[ \t]*=[ \t]*/, "", line)
      printf "%s ", line
      if (!cont) exit
    }' "$1"
}

echo "### local patches"
cp "$HERE/dropbear/ztpw.c" ./ztpw.c
for p in "$HERE"/dropbear/*.patch; do
  if patch -p1 --dry-run -s -f < "$p" >/dev/null 2>&1; then
    patch -p1 -s -f < "$p" || exit 1
    echo "applied $(basename "$p")"
  elif patch -p1 -R --dry-run -s -f < "$p" >/dev/null 2>&1; then
    echo "already applied $(basename "$p")"
  else
    echo "CANNOT APPLY $(basename "$p")"; exit 1
  fi
done

echo "### generated headers"
# configure leaves this to make; replicate the rule so options.h resolves.
# Always regenerate so edits to default_options.h take effect.
{
  printf '/*\n > > > Do not edit this file (default_options_guard.h) < < <\n*/\n\n'
  sh ./ifndef_wrapper.sh < default_options.h
} > default_options_guard.h

echo "### libtommath"
if [ -s libtommath/libtommath.a ] && [ "$(wc -c < libtommath/libtommath.a)" -gt 10000 ]; then
  echo "libtommath: cached"
else
  cd libtommath || exit 1
  LTM_OBJS=$(objlist Makefile)
  [ -n "$LTM_OBJS" ] || { echo "could not read OBJECTS from libtommath/Makefile"; exit 1; }
  for o in $LTM_OBJS; do
    c="${o%.o}.c"
    [ -f "$c" ] || { echo "missing source for $o"; exit 1; }
    cc -c "$c" -o "$o" -I. -I.. -DLTC_SOURCE || exit 1
  done
  "$ZIG" ar rcs libtommath.a $LTM_OBJS || exit 1
  echo "libtommath: built"
  cd .. || exit 1
fi

echo "### libtomcrypt"
if [ -s libtomcrypt/libtomcrypt.a ] && [ "$(wc -c < libtomcrypt/libtomcrypt.a)" -gt 10000 ]; then
  echo "libtomcrypt: cached"
else
  cd libtomcrypt || exit 1
  LTC_OBJS=$(objlist Makefile)
  [ -n "$LTC_OBJS" ] || { echo "could not read OBJECTS from libtomcrypt/Makefile"; exit 1; }
  LTC_FLAGS="-Isrc/headers/ -I../ -DLTC_SOURCE -I../libtommath/"
  for o in $LTC_OBJS; do
    c="${o%.o}.c"
    case "$o" in
      *aes_enc.o) cc $LTC_FLAGS -DENCRYPT_ONLY -c src/ciphers/aes/aes.c -o "$o" || exit 1 ;;
      *)
        [ -f "$c" ] || { echo "missing source for $o"; exit 1; }
        cc $LTC_FLAGS -c "$c" -o "$o" || exit 1
        ;;
    esac
  done
  "$ZIG" ar rcs libtomcrypt.a $LTC_OBJS || exit 1
  echo "libtomcrypt: built"
  cd .. || exit 1
fi

echo "### dropbear objects"
DB_FLAGS="-I. -Ilibtomcrypt/src/headers/ -DDROPBEAR_SERVER"
COMMON="dbutil.o buffer.o dbhelpers.o dss.o bignum.o signkey.o rsa.o dbrandom.o queue.o atomicio.o compat.o fake-rfc2553.o ltc_prng.o ecc.o ecdsa.o sk-ecdsa.o crypto_desc.o curve25519.o ed25519.o sk-ed25519.o dbmalloc.o gensignkey.o gendss.o genrsa.o gened25519.o ztpw.o"
CLISVR="common-session.o packet.o common-algo.o common-kex.o common-channel.o common-chansession.o termcodes.o loginrec.o tcp-accept.o listener.o process-packet.o dh_groups.o common-runopts.o circbuffer.o list.o netio.o chachapoly.o gcm.o"
SVR="svr-kex.o svr-auth.o sshpty.o svr-authpasswd.o svr-authpubkey.o svr-authpubkeyoptions.o svr-session.o svr-service.o svr-chansession.o svr-runopts.o svr-agentfwd.o svr-main.o svr-x11fwd.o svr-tcpfwd.o svr-authpam.o"
for o in $COMMON $CLISVR $SVR dropbearkey.o; do
  c="${o%.o}.c"
  [ -f "$c" ] || { echo "missing source for $o"; exit 1; }
  cc -c "$c" -o "$o" $DB_FLAGS || { echo "FAIL $c"; exit 1; }
done

echo "### link"
cc -static -o dropbear $COMMON $CLISVR $SVR libtomcrypt/libtomcrypt.a libtommath/libtommath.a || exit 1
cc -static -o dropbearkey $COMMON dropbearkey.o libtomcrypt/libtomcrypt.a libtommath/libtommath.a || exit 1
echo "### DONE"
file dropbear dropbearkey 2>/dev/null || true
ls -l dropbear dropbearkey
